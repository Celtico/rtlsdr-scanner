/** Country for a 6-hex-digit ICAO address, or null if unallocated. */
export function icaoCountry(icao: string): string | null {
  const n = parseInt(icao, 16);
  if (!Number.isFinite(n)) return null;
  let lo = 0;
  let hi = BLOCKS.length - 1;
  while (lo <= hi) {
    const mid = (lo + hi) >> 1;
    const b = BLOCKS[mid]!;
    if (n < b[0]) hi = mid - 1;
    else if (n > b[1]) lo = mid + 1;
    else return b[2];
  }
  return null;
}
